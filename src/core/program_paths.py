"""Program-directory path registry — the single Zone-A source of truth for
where platform-owned artifacts live under ``programs/<id>/``.

This module is the deliverable of ``specs/declutter.md`` Phase 0.5 / 1-B and
realizes goal G-7 (single source of truth for the directory taxonomy). Two
explicit registries drive every consumer:

* ``RUNTIME_ARTIFACTS`` — the T-3 platform-internal files that live in
  ``runtime/`` after the Phase 1-B flip. Each entry pairs a **canonical write
  getter** (``get_*_path`` — always returns ``runtime/<file>``; **never falls
  back**) with a **transitional read resolver** (``resolve_*_path_for_read`` —
  canonical-first, legacy fallback during the Phase 1 compatibility window;
  carries a ``# TODO-DC02`` marker to be removed per Phase 1-E). R-14: a
  writer must never call a fallback resolver, or active programs keep writing
  the legacy root path and create split-brain state.

* ``ROOT_ENTRIES`` — the T-1 authored config, T-2 mutable state, root T-4
  append-only logs, hidden markers, and recognized subdirectories. This is the
  whitelist ``DC-01-c`` derives from.

Phase 1-B status (2026-06-23): getters return ``runtime/<file>``; resolvers
prefer canonical and fall back to the legacy root during the transition window.
All ~22 production call sites already route through the correct getter or
resolver from Phase 0.5, so no call-site changes are needed.

``PROGRAMS_ROOT`` is imported from ``config_loader`` (the foundational default
used by most stores). Edition-resolution paths continue to use
``edition_resolver``'s env-aware root; runtime-path callers pass an explicit
``programs_root`` in tests, so the default source does not diverge in practice.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Literal

from src.core.config_loader import PROGRAMS_ROOT

# Subdirectory that collects platform-internal T-3 files (Phase 1-A).
RUNTIME_SUBDIR = "runtime"


def get_runtime_dir(program_id: str, *, programs_root: Path = PROGRAMS_ROOT) -> Path:
    """Canonical path for the platform-internal ``runtime/`` subdir.

    Phase 1-A: writers construct canonical runtime paths as
    ``get_runtime_dir(program_id, programs_root=...) / artifact.filename``.
    """
    return programs_root / program_id / RUNTIME_SUBDIR


# ---------------------------------------------------------------------------
# Runtime-artifact registry (T-3 files that move into runtime/)
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class RuntimeArtifact:
    """One platform-internal T-3 file with its tier and delete-safety contract.

    ``canonical_getter_name`` names the write getter (no legacy fallback);
    ``read_resolver_name`` names the transitional read resolver (canonical-first,
    legacy fallback during the Phase 1 compatibility window).
    """

    name: str
    filename: str
    tier: Literal["T-3a", "T-3b"]
    legacy_rel: PurePosixPath
    canonical_rel: PurePosixPath
    delete_safe: bool
    retention: str
    canonical_getter_name: str
    read_resolver_name: str
    checkpointed: bool = False


def _runtime(filename: str) -> PurePosixPath:
    return PurePosixPath(RUNTIME_SUBDIR) / filename


