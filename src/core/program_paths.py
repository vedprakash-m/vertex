# ---------------------------------------------------------------------------
# Transitional read resolvers (Phase 1-B)
#
# Prefer the canonical ``runtime/`` path; fall back to the legacy root only
# when the canonical file does not yet exist (pre-migration window). The
# fallback branches carry ``# TODO-DC02`` markers and are removed per the
# Phase 1-E lifecycle (command-matrix gate + 2 clean DC-02 runs).
#
# R-14: writers MUST NOT call these resolvers — use the canonical write getter.
# ---------------------------------------------------------------------------


def resolve_gather_state_path_for_read(program_id: str, *, programs_root: Path = PROGRAMS_ROOT) -> Path:
    canonical = get_gather_state_path(program_id, programs_root=programs_root)
    if not canonical.exists():
        legacy = programs_root / program_id / "gather_state.json"
        if legacy.exists():
            return legacy  # TODO-DC02 transition fallback; remove per Phase 1-E
    return canonical


